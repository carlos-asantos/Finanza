/**
 * Strict Brazilian Real (BRL) currency formatter.
 * Guarantees standard Brazilian real representation: "R$ 1.234,56"
 * regardless of whether English or Portuguese is selected.
 */
export function formatBRL(amount: number): string {
  if (isNaN(amount) || amount === undefined || amount === null) {
    return 'R$ 0,00';
  }

  const isNegative = amount < 0;
  const absVal = Math.abs(amount);

  const formatted = new Intl.NumberFormat('pt-BR', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(absVal);

  return `${isNegative ? '-' : ''}R$ ${formatted}`;
}

export function formatBRLRaw(amount: number): string {
  if (isNaN(amount) || amount === undefined || amount === null) {
    return '0,00';
  }
  const isNegative = amount < 0;
  const absVal = Math.abs(amount);
  const formatted = new Intl.NumberFormat('pt-BR', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(absVal);
  return `${isNegative ? '-' : ''}${formatted}`;
}

export function formatMonthLabel(year: number, month: number, lang: Language): string {
  const date = new Date(year, month - 1, 15);
  const locale = lang === 'pt' ? 'pt-BR' : 'en-US';
  const monthName = date.toLocaleDateString(locale, { month: 'long' });
  const capitalized = monthName.charAt(0).toUpperCase() + monthName.slice(1);
  return `${capitalized} ${year}`;
}

/**
 * Strict Brazilian / European standard date formatter: dd/mm/yyyy
 * Formats string date (YYYY-MM-DD or ISO timestamp) or Date object reliably
 * without timezone day shifting.
 */
export function formatDateDDMMYYYY(dateInput: string | Date | undefined | null): string {
  if (!dateInput) return '';
  if (typeof dateInput === 'string') {
    const match = dateInput.match(/^(\d{4})-(\d{2})-(\d{2})/);
    if (match) {
      const [, y, m, d] = match;
      return `${d}/${m}/${y}`;
    }
  }
  const d = new Date(dateInput);
  if (isNaN(d.getTime())) return '';
  const day = String(d.getDate()).padStart(2, '0');
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const year = d.getFullYear();
  return `${day}/${month}/${year}`;
}
